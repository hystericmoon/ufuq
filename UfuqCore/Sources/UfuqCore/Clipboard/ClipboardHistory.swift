import Foundation

public struct ClipboardItem: Equatable, Sendable, Identifiable {
    public var id: UUID
    public var text: String
    public var preview: String
    public var copiedAt: Date
    public var sourceApp: String?
    public var isPinned: Bool

    public init(
        id: UUID = UUID(),
        text: String,
        copiedAt: Date = Date(),
        sourceApp: String? = nil,
        isPinned: Bool = false
    ) {
        self.id = id
        self.text = text
        self.preview = Self.makePreview(from: text)
        self.copiedAt = copiedAt
        self.sourceApp = sourceApp
        self.isPinned = isPinned
    }

    public static func makePreview(from text: String, maxLength: Int = 100) -> String {
        let collapsed = text
            .components(separatedBy: .whitespacesAndNewlines)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
        guard collapsed.count > maxLength else { return collapsed }
        return String(collapsed.prefix(maxLength)) + "…"
    }
}

public struct ClipboardHistory: Equatable, Sendable {
    public var maxItems: Int
    public private(set) var items: [ClipboardItem]

    public static let ignoredPasteboardTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
    ]

    public init(maxItems: Int = 30, items: [ClipboardItem] = []) {
        self.maxItems = max(1, maxItems)
        self.items = items
    }

    public static func shouldIgnore(pasteboardTypes: [String]) -> Bool {
        pasteboardTypes.contains { ignoredPasteboardTypes.contains($0) }
    }

    @discardableResult
    public mutating func record(text: String, sourceApp: String? = nil, at now: Date = Date()) -> Bool {
        let trimmed = text.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }

        if let index = items.firstIndex(where: { $0.text == text }) {
            var existing = items.remove(at: index)
            existing.copiedAt = now
            if let sourceApp { existing.sourceApp = sourceApp }
            items.insert(existing, at: 0)
        } else {
            items.insert(ClipboardItem(text: text, copiedAt: now, sourceApp: sourceApp), at: 0)
        }
        sortAndTrim()
        return true
    }

    public mutating func togglePin(id: UUID) {
        guard let index = items.firstIndex(where: { $0.id == id }) else { return }
        items[index].isPinned.toggle()
        sortAndTrim()
    }

    public mutating func remove(id: UUID) {
        items.removeAll { $0.id == id }
    }

    public mutating func clearUnpinned() {
        items.removeAll { !$0.isPinned }
    }

    public func filtered(query: String) -> [ClipboardItem] {
        let q = query.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !q.isEmpty else { return items }
        return items.filter {
            $0.text.localizedCaseInsensitiveContains(q)
                || ($0.sourceApp?.localizedCaseInsensitiveContains(q) ?? false)
        }
    }

    private mutating func sortAndTrim() {
        let pinned = items.filter(\.isPinned).sorted { $0.copiedAt > $1.copiedAt }
        let unpinned = items.filter { !$0.isPinned }.sorted { $0.copiedAt > $1.copiedAt }
        let allowedUnpinned = max(0, maxItems - pinned.count)
        items = pinned + Array(unpinned.prefix(allowedUnpinned))
    }
}
